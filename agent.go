// =========================================================================
// Agent — implements acp.Agent, handles one ACP connection
// =========================================================================

var _ acp.Agent = (*Agent)(nil)

type Agent struct {
	cfg         Config
	llmProvider LLMConfigProvider
	modelInfo   ModelInfoProvider
	conn        *acp.AgentSideConnection
	sessionID   string
	sessionMu   sync.Mutex
}

func NewAgent(cfg Config, llmProvider LLMConfigProvider, modelInfo ModelInfoProvider) *Agent {
	return &Agent{
		cfg:         cfg,
		llmProvider: llmProvider,
		modelInfo:   modelInfo,
	}
}

func (a *Agent) SetConnection(conn *acp.AgentSideConnection) {
	a.conn = conn
}

func (a *Agent) getSession() string {
	a.sessionMu.Lock()
	defer a.sessionMu.Unlock()
	return a.sessionID
}

func (a *Agent) setSession(id string) {
	a.sessionMu.Lock()
	defer a.sessionMu.Unlock()
	a.sessionID = id
}

func (a *Agent) clearSession() {
	a.sessionMu.Lock()
	defer a.sessionMu.Unlock()
	a.sessionID = ""
}

// OnDisconnect marks the current session as idle when the connection drops.
func (a *Agent) OnDisconnect(ctx context.Context) {
	sid := a.getSession()
	if sid == "" {
		return
	}
	a.clearSession()
	sm := GetSessionManager()
	if s, ok := sm.GetCached(sid); ok && s.Status() == "active" {
		sm.MarkIdle(ctx, sid)
	}
}

